// ------------------------------------------------------------------ calibration helper
function calibrator(container, source, w, hgt, onChange) {
  const st = h(`<div class="instrument" style="cursor:crosshair"><canvas class="base"></canvas></div>`);
  container.append(st);
  const cv = st.querySelector('canvas');
  cv.width = w; cv.height = hgt;
  const ctx = cv.getContext('2d');
  let pts = [];
  const redraw = () => {
    ctx.drawImage(source, 0, 0, w, hgt);
    const lw = Math.max(2, w / 450);
    ctx.lineWidth = lw;
    if (pts.length) {
      ctx.beginPath(); pts.forEach((p, i) => i ? ctx.lineTo(...p) : ctx.moveTo(...p));
      if (pts.length === 4) ctx.closePath();
      ctx.strokeStyle = '#ffffff'; ctx.stroke();
    }
    pts.forEach((p, i) => {
      ctx.beginPath(); ctx.arc(p[0], p[1], Math.max(9, w / 110), 0, 7); ctx.fillStyle = '#ffffff'; ctx.fill();
      ctx.fillStyle = '#111316'; ctx.font = `600 ${Math.max(11, w / 95)}px "Geist Mono", monospace`; ctx.textAlign = 'center'; ctx.textBaseline = 'middle';
      ctx.fillText(String(i + 1), p[0], p[1] + 1);
    });
  };
  redraw();
  cv.addEventListener('click', e => {
    const r = cv.getBoundingClientRect();
    if (pts.length >= 4) pts = [];
    pts.push([(e.clientX - r.left) * w / r.width, (e.clientY - r.top) * hgt / r.height].map(v => Math.round(v * 10) / 10));
    redraw(); onChange(pts);
  });
  return { points: () => pts };
}


function videos(pane) {
  const ui = h(`<div class="stack">
    <p class="note">${CALIB_HELP} The rectangle defines the shared ground frame in metres. Both cameras must be static.</p>
    <div class="row" style="gap:1rem">
      <label class="field"><span>Width 1→2, m</span><input type="number" id="rw" value="2.5" step="0.1" min="0.2"></label>
      <label class="field"><span>Length 2→3, m</span><input type="number" id="rl" value="5.0" step="0.1" min="0.2"></label>
      <label class="field"><span>B starts later by, s</span><input type="number" id="off" value="0" step="0.1"></label>
      <button class="btn primary" id="run" disabled style="align-self:flex-end">Fuse on server <span class="arr">→</span></button>
    </div>
    <div class="progress"><div id="pbar"></div></div>
    <div class="cols c2">
      ${['A', 'B'].map(k => `<div class="stack" id="cam${k}">
        <span class="label">Camera ${k}</span>
        <label class="drop" style="min-height:110px"><input type="file" accept="video/*"><b>Choose video ${k}</b><span class="faint">static camera, same scene</span></label>
        <div class="calib"></div>
        <p class="mono faint geo" style="font-size:.78rem"></p>
        <div class="instrument hidden play"><video playsinline muted></video><canvas class="overlay"></canvas><span class="tag">camera ${k}</span><div class="alertbar hidden"><i></i><span></span></div></div>
        <div class="alerts"></div>
      </div>`).join('')}
    </div>
    <div class="work"><canvas class="bev" id="bev"></canvas><div class="panel"><span class="label">Fused objects</span><div id="objs" class="mono faint" style="font-size:.8rem">—</div></div></div>
  </div>`);
  pane.append(ui);
  const cams = { A: {}, B: {} };
  const bev = new BEV(ui.querySelector('#bev'));
  let frames = [], job = null, raf = 0;
  const ready = () => { ui.querySelector('#run').disabled = !(cams.A.pts?.length === 4 && cams.B.pts?.length === 4); };
  const calibJson = k => ({ width: cams[k].w, height: cams[k].h, image_points: cams[k].pts, rect_w: +ui.querySelector('#rw').value, rect_l: +ui.querySelector('#rl').value });

  for (const k of ['A', 'B']) {
    const box = ui.querySelector(`#cam${k}`);
    const input = box.querySelector('input[type=file]');
    box.querySelector('.drop').onclick = () => input.click();
    input.onchange = async () => {
      const f = input.files[0]; if (!f) return;
      cams[k].file = f;
      const v = document.createElement('video');
      v.muted = true; v.playsInline = true; v.src = URL.createObjectURL(f);
      await new Promise(r => { v.onloadeddata = r; });
      v.currentTime = Math.min(0.5, v.duration / 2);
      await new Promise(r => { v.onseeked = r; });
      cams[k].w = v.videoWidth; cams[k].h = v.videoHeight;
      const cal = box.querySelector('.calib'); cal.innerHTML = '';
      calibrator(cal, v, v.videoWidth, v.videoHeight, async pts => {
        cams[k].pts = pts; ready();
        const g = box.querySelector('.geo');
        if (pts.length !== 4) { g.textContent = `${pts.length} of 4 points`; return; }
        try {
          const d = await api('/api/v1/guardian/calibrate', { method: 'POST', json: calibJson(k) });
          g.innerHTML = `height ${d.height_m} m · tilt ${d.pitch_deg}° · focal ${d.focal_px} px · fit ±${d.calib_rmse_m} m${d.warnings.length ? `<br><span class="error">${esc(d.warnings.join('; '))}</span>` : ''}`;
        } catch (e) { g.innerHTML = `<span class="error">${esc(e.message)}</span>`; }
      });
      box.querySelector('.play video').src = v.src;
    };
  }

  ui.querySelector('#run').onclick = async () => {
    if (job) job.cancel();
    frames = []; bev.view = null;
    const fd = new FormData();
    fd.append('video_a', cams.A.file); fd.append('video_b', cams.B.file);
    fd.append('calib_a', JSON.stringify(calibJson('A'))); fd.append('calib_b', JSON.stringify(calibJson('B')));
    fd.append('offset_s', ui.querySelector('#off').value);
    ui.querySelector('#run').disabled = true;
    try {
      const r = await api('/api/v1/guardian/videos', { method: 'POST', body: fd });
      for (const k of ['A', 'B']) { const box = ui.querySelector(`#cam${k}`); box.querySelector('.calib').classList.add('hidden'); box.querySelector('.play').classList.remove('hidden'); }
      job = streamJob(r.job_id, {
        frame: m => frames.push(m),
        progress: p => { ui.querySelector('#pbar').style.width = `${Math.round(p * 100)}%`; },
        warning: w => { ui.querySelector('#objs').textContent = w; },
        done: () => {
          ui.querySelector('#run').disabled = false;
          for (const k of ['A', 'B']) { const v = ui.querySelector(`#cam${k} .play video`); v.currentTime = k === 'B' ? +ui.querySelector('#off').value : 0; v.play().catch(() => {}); }
        },
        error: e => { ui.querySelector('#run').disabled = false; ui.querySelector('#objs').innerHTML = `<span class="error">${esc(e)}</span>`; },
      });
    } catch (e) { ui.querySelector('#run').disabled = false; ui.querySelector('#objs').innerHTML = `<span class="error">${esc(e.message)}</span>`; }
  };

  const loop = () => {
    const vA = ui.querySelector('#camA .play video');
    if (frames.length && vA && !vA.paused) {
      const t = vA.currentTime;
      let m = null; for (const f of frames) { if (f.t <= t + 0.05) m = f; else break; }
      if (m) {
        for (const k of ['A', 'B']) {
          const box = ui.querySelector(`#cam${k}`);
          drawCamView(box.querySelector('.play canvas'), m.views[k], cams[k].w, c => `camera ${c}`);
          box.querySelector('.alerts').innerHTML = alertsHtml(m.views[k].alerts, c => `camera ${c}`);
          const hidden = m.views[k].alerts.filter(a => a.status === 'occluded');
          const bar = box.querySelector('.alertbar');
          bar.classList.toggle('hidden', !hidden.length);
          if (hidden.length) bar.querySelector('span').textContent = `${hidden.length} hidden: ${hidden.map(a => pretty(a.cls)).join(', ')}`;
        }
        if (!bev.view) bev.fit([...m.fov.A, ...m.fov.B], 3);
        drawWorld(bev, { cams: { A: { fov: m.fov.A, pos: m.pos.A, label: 'A' }, B: { fov: m.fov.B, pos: m.pos.B, label: 'B' } }, ego: 'A', objects: m.views.A.objects });
        ui.querySelector('#objs').innerHTML = m.views.A.objects.map(o => `${esc(pretty(o.cls))} g${o.gid} · (${o.xy[0]}, ${o.xy[1]}) m · ±${o.r2s} m · ${o.sources.join('+')} · ${o.status} for A`).join('<br>') || 'no objects';
      }
      const vB = ui.querySelector('#camB .play video');
      const want = t + +ui.querySelector('#off').value;
      if (vB && Math.abs(vB.currentTime - want) > 0.3) vB.currentTime = want;
    }
    raf = requestAnimationFrame(loop);
  };
  raf = requestAnimationFrame(loop);
  return () => { if (job) job.cancel(); cancelAnimationFrame(raf); };
}

// ------------------------------------------------------------------ live room with phones
function live(pane, args) {
  const room = (args[0] || Math.random().toString(36).slice(2, 6)).toUpperCase();
  const link = `${location.origin}${location.pathname}#/guardian/live/${room}`;
  const ui = h(`<div class="stack">
    <div class="row between">
      <div><span class="label">Room</span><div class="mono" style="font-size:1.6rem;letter-spacing:.08em">${room}</div>
        <p class="faint" style="font-size:.84rem">Open on every device: <a class="mono" href="${link}">${link}</a></p></div>
      <div class="seg" id="roles"><button data-r="A">Camera A</button><button data-r="B">Camera B</button><button data-r="viewer">Viewer</button></div>
    </div>
    <p class="note">Put two phones on stands looking at the same area from different angles, for example with one view blocked by a parked car.
      ${CALIB_HELP} Each phone sends 3–5 frames per second. Alerts show the measured latency from the other camera's capture to this screen.</p>
    <p class="mono faint" id="roster" style="font-size:.8rem">connecting…</p>
    <div id="work"></div>
  </div>`);
  pane.append(ui);
  let ws = null, stream = null, timer = 0, offset = 0;
  const work = ui.querySelector('#work');

  function connect(onMsg) {
    ws = new WebSocket(wsUrl(`/ws/guardian/${room}`));
    const pings = [];
    ws.onopen = () => { for (let i = 0; i < 5; i++) setTimeout(() => ws?.readyState === 1 && ws.send(JSON.stringify({ type: 'ping', t: Date.now() })), i * 150); };
    ws.onmessage = ev => {
      const m = JSON.parse(ev.data);
      if (m.type === 'pong') {
        const now = Date.now(), rtt = now - m.t;
        pings.push({ rtt, off: m.server - (m.t + rtt / 2) });
        offset = pings.sort((a, b) => a.rtt - b.rtt)[0].off;
      } else if (m.type === 'roster') {
        const cs = Object.values(m.info.cameras);
        ui.querySelector('#roster').textContent = `cameras: ${cs.map(c => `${c.cam}${c.calibrated ? ' (calibrated)' : ' (not calibrated)'}`).join(', ') || 'none'} · viewers ${m.info.viewers} · clock offset ${Math.round(offset)} ms`;
      }
      onMsg?.(m);
    };
    ws.onclose = () => { ui.querySelector('#roster').textContent = 'disconnected'; };
  }

  ui.querySelector('#roles').onclick = e => {
    const r = e.target.dataset.r; if (!r) return;
    stop();
    ui.querySelectorAll('#roles button').forEach(b => b.classList.toggle('active', b.dataset.r === r));
    return r === 'viewer' ? viewer() : camera(r);
  };

  function viewer() {
    work.innerHTML = '';
    const v = h(`<div class="work"><canvas class="bev" id="bev"></canvas><div class="panel"><span class="label">Alerts per camera</span><div id="va"></div></div></div>`);
    work.append(v);
    const bev = new BEV(v.querySelector('#bev'));
    connect(m => {
      if (m.type === 'welcome') ws.send(JSON.stringify({ type: 'hello', role: 'viewer' }));
      if (m.type !== 'world') return;
      const pts = Object.values(m.cams).flatMap(c => c.fov || []);
      if (pts.length) { bev.fit(pts, 2); drawWorld(bev, { cams: Object.fromEntries(Object.entries(m.cams).map(([k, c]) => [k, { ...c, label: k }])), objects: m.objects.map(o => ({ ...o, status: 'visible' })) }); }
      v.querySelector('#va').innerHTML = Object.entries(m.alerts).map(([c, a]) => `<span class="label" style="display:block;margin:.6rem 0 .2rem">camera ${esc(c)}</span>${alertsHtml(a, x => 'camera ' + x)}`).join('');
    });
  }

  async function camera(cam) {
    work.innerHTML = '';
    const v = h(`<div class="work"><div class="stack">
        <div class="instrument"><video playsinline muted autoplay></video><canvas class="overlay"></canvas><span class="tag">camera ${cam}</span><div class="alertbar hidden"><i></i><span></span></div></div>
        <div class="row" style="gap:.8rem">
          <button class="btn" id="freeze">Calibrate: freeze frame</button>
          <label class="field"><span>Width 1→2, m</span><input type="number" id="rw" value="2.5" step="0.1"></label>
          <label class="field"><span>Length 2→3, m</span><input type="number" id="rl" value="5" step="0.1"></label>
          <button class="btn primary" id="send" disabled style="align-self:flex-end">Start streaming</button></div>
        <div id="cal"></div><p class="mono faint" id="geo" style="font-size:.78rem"></p>
      </div>
      <aside><div class="panel"><span class="label">Network alerts for camera ${cam}</span><div id="al"><p class="faint">Calibrate to start.</p></div></div>
        <div class="panel"><span class="label">Latency</span><div id="lat" class="mono faint" style="font-size:.8rem">—</div></div></aside></div>`);
    work.append(v);
    const video = v.querySelector('video');
    try {
      stream = await navigator.mediaDevices.getUserMedia({ video: { facingMode: { ideal: 'environment' }, width: { ideal: 1280 } }, audio: false });
    } catch (e) { v.querySelector('#geo').innerHTML = `<span class="error">Camera unavailable: ${esc(e.message)}. HTTPS and permission are required.</span>`; return; }
    video.srcObject = stream; await video.play();
    const W = 640, scale = () => W / Math.max(video.videoWidth, video.videoHeight);
    let pts = [], streaming = false, busy = false;
    const lat = [];
    connect(m => {
      if (m.type === 'welcome') ws.send(JSON.stringify({ type: 'hello', role: 'camera', cam }));
      if (m.type === 'calib_ok') { v.querySelector('#geo').textContent = `calibrated · height ${m.geometry.height_m} m · tilt ${m.geometry.pitch_deg}° · focal ${m.geometry.focal_px} px`; streaming = true; }
      if (m.type === 'calib_error') v.querySelector('#geo').innerHTML = `<span class="error">${esc(m.error)}</span>`;
      if (m.type === 'view') {
        if (m.source_cam === cam) busy = false;
        const e2e = Date.now() + offset - m.source_capture_ms;
        if (m.source_cam !== cam) { lat.push(e2e); if (lat.length > 50) lat.shift(); }
        const med = lat.length ? [...lat].sort((a, b) => a - b)[Math.floor(lat.length / 2)] : null;
        v.querySelector('#lat').innerHTML = `server processing ${m.processing_ms} ms · upload ${m.upload_ms} ms<br>${med != null ? `other camera's capture → alert here: median ${Math.round(med)} ms (n ${lat.length})` : 'waiting for observations from another camera'}`;
        drawCamView(v.querySelector('canvas'), m, Math.round(video.videoWidth * scale()), c => 'camera ' + c);
        v.querySelector('#al').innerHTML = alertsHtml(m.alerts, c => 'camera ' + c);
        const hidden = m.alerts.filter(a => a.status === 'occluded');
        const bar = v.querySelector('.alertbar');
        bar.classList.toggle('hidden', !hidden.length);
        if (hidden.length) bar.querySelector('span').textContent = `Hidden ${pretty(hidden[0].cls)} ${hidden[0].distance_m} m behind ${pretty(hidden[0].occluded_by?.cls)}, seen by camera ${hidden[0].sources.join(', ')}`;
      }
    });
    v.querySelector('#freeze').onclick = () => {
      const c = document.createElement('canvas');
      const s = scale();
      c.width = Math.round(video.videoWidth * s); c.height = Math.round(video.videoHeight * s);
      c.getContext('2d').drawImage(video, 0, 0, c.width, c.height);
      const cal = v.querySelector('#cal'); cal.innerHTML = '';
      calibrator(cal, c, c.width, c.height, p => { pts = p; v.querySelector('#send').disabled = p.length !== 4; });
    };
    v.querySelector('#send').onclick = () => {
      const s = scale();
      ws.send(JSON.stringify({ type: 'calib', calib: { width: Math.round(video.videoWidth * s), height: Math.round(video.videoHeight * s), image_points: pts, rect_w: +v.querySelector('#rw').value, rect_l: +v.querySelector('#rl').value } }));
      v.querySelector('#cal').innerHTML = '';
    };
    const grab = document.createElement('canvas');
    let lastSent = 0;
    timer = setInterval(() => {
      if (!streaming || busy || !ws || ws.readyState !== 1 || Date.now() - lastSent < 200) return;
      const s = scale();
      grab.width = Math.round(video.videoWidth * s); grab.height = Math.round(video.videoHeight * s);
      grab.getContext('2d').drawImage(video, 0, 0, grab.width, grab.height);
      const tCap = Date.now();
      grab.toBlob(b => {
        if (!b || !ws || ws.readyState !== 1) return;
        busy = true; lastSent = Date.now();
        ws.send(JSON.stringify({ type: 'frame', t_capture: tCap, offset_ms: offset }));
        ws.send(b);
        setTimeout(() => { busy = false; }, 2500);
      }, 'image/jpeg', 0.7);
    }, 50);
  }

  function stop() {
    clearInterval(timer); timer = 0;
    if (ws) { try { ws.close(); } catch {} ws = null; }
    if (stream) { stream.getTracks().forEach(t => t.stop()); stream = null; }
  }
  if (args[1] === 'viewer') viewer();
  return stop;
}
